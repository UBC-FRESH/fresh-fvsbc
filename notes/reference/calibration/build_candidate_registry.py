"""Build and check the frozen candidate registry.

The registry records each candidate card, its metrics, its calibration rule, and
its review status. It contains no site-level rows.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path("notes/reference/calibration")
POLICY = ROOT / "calibration-policy.json"
JSON_OUT = ROOT / "candidate-registry.json"
MARKDOWN_OUT = ROOT / "CANDIDATE-REGISTRY.md"
REVIEW_PENDING = {"quesnel", "okanagan"}
GROUPS_OVERRIDE = {
    "quesnel": ["FD", "HW", "OTHER", "SE"],
}
SCOPE_NOTES = {
    "quesnel": "non-PL background; PL is excluded",
    "north-island": "supported groups only; PL omitted",
    "fraser": "supported groups only; PL and SE omitted",
    "haida-gwaii": "supported groups only; PL omitted",
    "mackenzie": "supported groups only; FD omitted",
}


def _digest(path: Path) -> str:
    """Return a SHA-256 digest without loading the file into memory."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return "sha256:" + digest.hexdigest()


def _slug(path: Path) -> str:
    """Return the candidate slug from its card directory."""
    parent = path.parent.name
    return parent.removesuffix("-candidate")


def _n(card: dict[str, object]) -> int:
    """Return the aggregate interval count from a card."""
    metrics = card.get("metrics", [])
    if not isinstance(metrics, list):
        return 0
    for row in metrics:
        if isinstance(row, dict) and row.get("group") == "ALL":
            return int(float(row.get("n", 0)))
    for row in metrics:
        if isinstance(row, dict) and row.get("view") == "all":
            return int(float(row.get("n", 0)))
    values = [float(row.get("n", 0)) for row in metrics if isinstance(row, dict)]
    return int(max(values)) if values else 0


def _policy_rules() -> dict[str, str]:
    """Return the calibration rule label for each candidate slug."""
    policy = json.loads(POLICY.read_text())
    rules: dict[str, str] = {}
    for name in policy.get("supported", {}):
        rules[name] = "symmetric (supported)"
    for name in policy.get("one_sided", {}):
        rules[name] = "one-sided"
    for name in policy.get("optional_symmetric", []):
        rules[name] = "symmetric (optional)"
    for name in policy.get("optional_one_sided", []):
        rules[name] = "one-sided (optional)"
    return rules


def _entries() -> list[dict[str, object]]:
    """Return one registry entry per frozen candidate card."""
    cards = sorted(ROOT.glob("*-candidate/model-card.json"))
    rules = _policy_rules()
    entries = []
    for path in cards:
        card = json.loads(path.read_text())
        slug = _slug(path)
        metrics_path = path.parent / "metrics.csv"
        calibration = card.get("calibration", {})
        entries.append(
            {
                "slug": slug,
                "model_id": card["model_id"],
                "target_tsa": card["target_tsa"],
                "groups": GROUPS_OVERRIDE.get(slug, sorted(card.get("species_groups", {}))),
                "scope": SCOPE_NOTES.get(slug, "all supported groups"),
                "n": _n(card),
                "calibration_rule": rules.get(slug, "none"),
                "card_mode": calibration.get("mode", "unrecorded"),
                "review_status": "review_pending"
                if slug in REVIEW_PENDING
                else "not_in_current_review",
                "card": str(path),
                "card_sha256": _digest(path),
                "metrics": str(metrics_path) if metrics_path.is_file() else None,
                "metrics_sha256": _digest(metrics_path) if metrics_path.is_file() else None,
            }
        )
    if not entries:
        raise SystemExit("no candidate cards found")
    ids = [str(entry["model_id"]) for entry in entries]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate candidate model_id")
    return sorted(entries, key=lambda entry: str(entry["model_id"]))


def _payload() -> dict[str, object]:
    """Return the registry object."""
    entries = _entries()
    counts: dict[str, int] = {}
    for entry in entries:
        status = str(entry["review_status"])
        counts[status] = counts.get(status, 0) + 1
    return {
        "registry_id": "d9-candidate-registry-v0",
        "status": "frozen",
        "policy": str(POLICY),
        "review_package": str(ROOT / "d9-candidate-review-package.md"),
        "counts": counts,
        "candidates": entries,
    }


def _markdown(payload: dict[str, object]) -> str:
    """Return the human-readable registry table."""
    lines = [
        "# Candidate registry",
        "",
        "Generated by `build_candidate_registry.py`; do not edit by hand.",
        "",
        "| Model | TSA | Groups | n | Rule | Review |",
        "| --- | --- | --- | ---: | --- | --- |",
    ]
    for entry in payload["candidates"]:
        lines.append(
            "| `{model}` | {tsa} | {groups} | {n:,} | {rule} | {review} |".format(
                model=entry["model_id"],
                tsa=entry["target_tsa"],
                groups=", ".join(entry["groups"]),
                n=entry["n"],
                rule=entry["calibration_rule"],
                review=entry["review_status"],
            )
        )
    scoped = [entry for entry in payload["candidates"] if entry["scope"] != "all supported groups"]
    if scoped:
        lines.extend(["", "Scope notes:", ""])
        for entry in scoped:
            lines.append(f"- `{entry['model_id']}`: {entry['scope']}.")
    lines.extend(
        [
            "",
            "The registry contains no site-level rows. It is not a bundle or",
            "certificate.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    """Write or check the registry."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when the files are stale.")
    args = parser.parse_args()

    payload = _payload()
    text_json = json.dumps(payload, indent=2, sort_keys=True) + "\n"
    text_markdown = _markdown(payload)
    if args.check:
        if not JSON_OUT.is_file() or JSON_OUT.read_text() != text_json:
            raise SystemExit(f"stale registry: {JSON_OUT}")
        if not MARKDOWN_OUT.is_file() or MARKDOWN_OUT.read_text() != text_markdown:
            raise SystemExit(f"stale registry table: {MARKDOWN_OUT}")
        print(f"registry ok: {len(payload['candidates'])} candidates")
        return
    JSON_OUT.write_text(text_json)
    MARKDOWN_OUT.write_text(text_markdown)
    print(f"wrote {JSON_OUT} and {MARKDOWN_OUT}")


if __name__ == "__main__":
    main()
